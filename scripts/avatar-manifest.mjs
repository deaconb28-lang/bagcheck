#!/usr/bin/env node
/**
 * Rewrite `lib/avatars/manifest.ts` from what is actually in
 * `public/archetypes/`.
 *
 *   npm run avatars:manifest
 *
 * The manifest exists so `<Avatar>` knows which archetypes have generated art
 * without reading the filesystem at render time — a server component can, but
 * the answer has to reach the client bundle too, and a directory listing is
 * not something a page should do on every paint.
 *
 * Generated, never hand-edited: the file on disk is the truth, and a
 * hand-maintained list would eventually claim art that is not there.
 */

import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ARCHETYPES } from "../lib/archetypes.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = join(ROOT, "public", "archetypes");

const drawn = existsSync(DIR)
  ? new Set(
      readdirSync(DIR)
        .filter((f) => f.endsWith(".png"))
        .map((f) => f.replace(/\.png$/, "")),
    )
  : new Set();

const have = ARCHETYPES.filter((a) => drawn.has(a.key)).map((a) => a.key);
const missing = ARCHETYPES.filter((a) => !drawn.has(a.key)).map((a) => a.key);

const file = `/*
 * Generated by scripts/avatar-manifest.mjs — do not edit by hand.
 *
 * Which archetypes have a generated avatar in public/archetypes. Everything
 * not listed here renders the drawn emblem from ./drawn.ts, which is a
 * finished state rather than a placeholder.
 */

export const GENERATED_AVATARS: ReadonlySet<string> = new Set([
${have.map((k) => `  "${k}",`).join("\n")}
]);

export function hasGeneratedAvatar(key: string): boolean {
  return GENERATED_AVATARS.has(key);
}

/** The static path. Immutable once generated, so it is cached hard. */
export function avatarSrc(key: string): string {
  return \`/archetypes/\${key}.png\`;
}
`;

writeFileSync(join(ROOT, "lib", "avatars", "manifest.ts"), file);
console.log(`${have.length}/16 generated${missing.length ? ` · drawn: ${missing.join(" ")}` : ""}`);
